<?php
declare(strict_types=1);

namespace App\Libraries\PromptMaker;

/**
 * BasePromptMaker: كلاس أساسي لبناء التوجيهات
 * كل أداة ترث منه وتنفذ buildSystemPrompt و buildUserPrompt
 */
abstract class BasePromptMaker
{
    /**
     * بناء system prompt من base prompt + بيانات الأداة
     */
    abstract public function buildSystemPrompt(string $basePrompt, array $payload): string;

    /**
     * بناء user prompt من payload
     */
    abstract public function buildUserPrompt(array $payload): string;

    /**
     * إرجاع رسائل جاهزة {system, user}
     *
     * يدعم task_prompt_mode (مُخزَّن في payload['__task_prompt_mode']):
     *   append  — يُضيف task_prompt بعد system_prompt  (الإعداد الافتراضي)
     *   prepend — يُضيف task_prompt قبل system_prompt
     *   replace — يستبدل system_prompt بـ task_prompt (إن وُجد)
     *   ignore  — لا يُضيف task_prompt إطلاقاً
     */
    public function buildMessages(string $basePrompt, array $payload): array
    {
        $mode       = (string)($payload['__task_prompt_mode'] ?? 'append');
        $taskPrompt = trim((string)($payload['task_prompt'] ?? ''));

        // دمج task_prompt مع system_prompt حسب الوضع المُحدَّد في قاعدة البيانات
        $finalSystemPrompt = match($mode) {
            'prepend' => $taskPrompt !== ''
                ? "السياق/وصف المهمة (Context / Task Prompt):\n{$taskPrompt}\n\n" . $basePrompt
                : $basePrompt,
            'replace' => $taskPrompt !== '' ? $taskPrompt : $basePrompt,
            'ignore'  => $basePrompt,
            default   => $taskPrompt !== ''  // append (default)
                ? $basePrompt . "\n\nالسياق/وصف المهمة (Context / Task Prompt):\n{$taskPrompt}"
                : $basePrompt,
        };

        return [
            'system' => $this->buildSystemPrompt($finalSystemPrompt, $payload),
            'user'   => $this->buildUserPrompt($payload),
        ];
    }

    /**
     * تنظيف القيم من مسافات ومحارف خفية
     */
    protected function cleanValue(?string $value): string
    {
        $value = (string) ($value ?? '');
        $value = str_replace(["\r\n", "\r", "\n"], ' ', $value);
        $value = str_replace(["\xE2\x80\x8F", "\xE2\x80\x8E", "\xC2\xA0"], ' ', $value);
        return trim($value);
    }

    /**
     * تحويل مصفوفة إلى نص
     */
    protected function arrayToText($arr, string $separator = '، '): string
    {
        if (!is_array($arr)) {
            return is_scalar($arr) ? (string)$arr : '';
        }
        $out = [];
        foreach ($arr as $x) {
            $out[] = is_scalar($x) ? (string)$x : json_encode($x, JSON_UNESCAPED_UNICODE);
        }
        return implode($separator, array_map('trim', $out));
    }

    /**
     * إرجاع قائمة معايير المعلمين كاملة لإدراجها في التوجيهات
     */
    protected function getTeacherStandards(): string
    {
        return <<<STDS
إليك جميع المعايير مرتبة بالتسلسل الهرمي كما وردت في الوثيقة:

**معيار المعلمين 1 - المعرفة المهنية**

*   **1.1 المعرفة بالمبحث**
    *   1.1.1 فهم المعرفة، بالمبحث أو المجال الذي سيتم تدريسه.
    *   1.1.2 امتلاك المعرفة اللازمة بالمحتوى لإيجاد خبرة ذات صلة وذات مغزى للمتعلّمين.
    *   1.1.3 إجادة اللغة العربية أو الإنجليزية حسب المبحث.
    *   1.1.4 امتلاك المعرفة بنمو الطفل (مع التركيز على الجانب النفسي للطفل).
    *   1.1.5 فهم أنواع التقييم المختلفة للتعلّم.

*   **1.2 المعرفة بالمحتوى التربوي**
    *   1.2.1 امتلاك المعرفة التربوية المناسبة بالمحتوى للمتعلمين ومجال الدراسة.
    *   1.2.2 فهم نظريات التعلم، وأهميتها في الممارسة.
    *   1.2.3 معرفة وفهم مبادئ وممارسات التعلم والتعليم والقائمة على الاستقصاء.

*   **1.3 المعرفة بالسياق**
    *   1.3.1 فهم الثقافة والتقاليد الأردنية وتأثيرها على الممارسة.
    *   1.3.2 القدرة على تحديد العوامل المتعلقة بخصائص المتعلم والبيئة الملائمة للتعلم.
    *   1.3.3 القدرة على تحديد القضايا الرئيسة المتعلقة بالطلبة ذوي الاحتياجات التعليمية الخاصة وصعوبات التعلم.

*   **1.4 المعرفة بالمنهاج**
    *   1.4.1 فهم متطلبات المنهاج الأردني.
    *   1.4.2 فهم المبادئ الأساسية لتخطيط المناهج وتصميمها.
    *   1.4.3 فهم المبادئ الأساسية لتقييم المنهاج.

**معيار المعلمين 2 - الممارسة المهنية**

*   **2.1 التخطيط**
    *   2.1.1 الاستخدام الفعال للمبحث والمعرفة بالمحتوى التربوي عند القيام بالتخطيط للتدريس وتقييم التعلم وتقويمه.
    *   2.1.2 اختيار استراتيجيات التدريس ومصادره (تشمل أدوات التعلّم الرقمية) وفقًا لحاجات الطلبة المختلفة.
    *   2.1.3 التخطيط للتدريس لتلبية احتياجات جميع المتعلمين وتمكينهم من مواكبة متطلبات أعمارهم بنجاح محلّيًا وعالمّيًا.

*   **2.2 التعلم والتعليم**
    *   2.2.1 التواصل بوضوح ودقة مع المتعلمين وأصحاب العلاقة.
    *   2.2.2 إنشاء واستخدام مجموعة متسلسلة من الخبرات والأنشطة المرتبطة بأهداف تعليمية واضحة ومناسبة؛ لتعزيز إنجازات المتعلم.
    *   2.2.3 صياغة توقعات عالية تلهم وتحفز المتعلمين والمحافظة على استدامتها.
    *   2.2.4 جمع أدلة واستخدامها بشكل منھجّي لتحسين التعليم والتعلم.
    *   2.2.5 بناء حجج منطقية مترابطة حول القضايا والممارسات التعليمية.
    *   2.2.6 توظيف أدوات التعلّم الرقمية المناسبة في تطوير التعلم.

*   **2.3 بيئة التعلم**
    *   2.3.1 إيجاد بيئة داعمة وآمنة للجميع والحفاظ عليها.
    *   2.3.2 خلق بيئة تعليمية وإدارتها بشكل فّعال لتمكين المتعلمين من التأّمل بتعلّمهم وتقييمه باستخدام التنظيم الذاتّي.

*   **2.4 التقييم**
    *   2.4.1 اعتماد نهج متوازن لاستخدام التقييم التكويني والختامي؛ لدعم تعلم الطالب.
    *   2.4.2 استخدام التمايز في الّتعلم والّتعليم لتلبية احتياجات الطالب على اختلاف قدراتهم.
    *   2.4.3 جمع وتحليل واستخدام التقييم؛ لتحسين التعلم والكشف عن نقاط القوة والقصور في التخطيط.

**معيار المعلمين 3 - أخلاقيات المهنة**

*   **3.1 المعلمون كمهنيين**
    *   3.1.1 العمل بفعالية مع المدرسة والمجتمع المحلي، بتوفير مستويات عالية من الخدمة.
    *   3.1.2 فهم وتنفيذ المسؤوليات والحقوق المهنية بشكل كامل.
    *   3.1.3 التعامل مع الآخرين بلطف واحترام ونزاهة.
    *   3.1.4 استخدام الموارد بنزاهة وتثقيف المتعلمين للقيام بذلك.
    *   3.1.5 إظهار الاحترام والتقدير والالتزام تجاه المجتمع الذي يعملون فيه.
    *   3.1.6 إيجاد قنوات تواصل مثمرة والحفاظ عليها مع أصحاب العلاقة.

*   **3.2 التنمية المهنية**
    *   3.2.1 إظهار المعرفة بضرورة الالتزام بالتطوير الشخصي والمهني مدى الحياة.
    *   3.2.2 إظهار الوعي بالبحوث التربوية ومساهمتها في التعلم والتعليم.
    *   3.2.3 التفكير بعمق في كيفية المساهمة الفّعالة في تطوير المناهج الدراسية والتخطيط لتطوير المدارس.
    *   3.2.4 تقدير المهنية من خلال تحمل الطلبة مسؤولية تعلمهم وتطورهم المهنّي.
STDS;
    }
}

