<?php
declare(strict_types=1);

namespace App\Libraries\PromptMaker;

/**
 * ForumReplyCommentPromptMaker: بناء توجيهات ردود على تعليقات الزملاء
 */
class ForumReplyCommentPromptMaker extends BasePromptMaker
{
    public function buildSystemPrompt(string $basePrompt, array $payload): string
    {
        if (trim($basePrompt) === '') {
            return <<<SYS
أنت خبير في كتابة تغذية راجعة احترافية على تعليقات منتدى تعليمية.
مهمتك صياغة رد واحد على تعليق منشور في منتدى أكاديمي، على شكل فقرة واحدة مترابطة وواضحة.
يجب أن:
- تحلل تعليق الزميل بدقة، وتربطه بسياق المهمة وتعليماتها قبل كتابة الرد.
- تكوّن رأيًا واضحًا وعميقًا حول جودة أداء المهمة وفهم المطلوب.
- تطبّق أسلوب "السندويتش" في التغذية الراجعة: بدءًا بالشكر والثناء على أداء المهمة، ثم إبراز نقاط القوة في الرد، وأخيرًا الإشارة إلى فرص التطوير أو التحسين.
- تناقش الطرح/الفكرة مباشرة (موافقة، اختلاف في الرأي، سؤال، توضيح، اقتراح، إضافة) دون توجيه الكلام لصاحب التعليق نفسه.
- لا تستخدم عبارات من نوع: "زميلي، زميلتي، معلم، معلمة" ولا تخاطب التعليق بصيغة "أنت".
- يخرج الرد بصيغة JSON صالحة فقط، بلا أي نص أو شرح خارج JSON.
SYS;
        }
        return trim($basePrompt);
    }

    public function buildUserPrompt(array $payload): string
    {
        $val = fn(?string $s): string => $this->cleanValue($s);
        
        $taskTitle       = $val($payload['task_title'] ?? '');
        $taskPrompt      = $val($payload['task_prompt'] ?? '');
        $commentText     = $val($payload['comment_text'] ?? '');
        $replyType       = $val($payload['reply_type'] ?? 'agreement');
        $replyInstructions = $val($payload['reply_instructions'] ?? '');
        $tone            = $val($payload['tone'] ?? 'formal');
        $audience        = $val($payload['audience'] ?? 'teachers');
        $studentAnswer   = $val($payload['student_answer'] ?? '');

        // ترجمة نوع الرد
        $replyTypeLabels = [
            'agreement'    => 'موافقة',
            'disagreement' => 'اختلاف بالرأي',
            'question'     => 'سؤال',
            'suggestion'   => 'اقتراح',
            'clarification'=> 'توضيح',
            'addition'     => 'إضافة',
        ];
        $replyTypeLabel = $replyTypeLabels[$replyType] ?? $replyType;

        $studentAnswerSection = '';
        if ($studentAnswer !== '') {
            $studentAnswerSection = <<<STU

ملاحظة خاصة من الطالب (تُستخدم لتمييز الرد وضمان فرديّته، دون نسخ حرفي):
{$studentAnswer}

تعليمات إلزامية حول هذه الملاحظة:
- استخرج منها ما يدعم تحليلك للتعليق أو يوضح زاوية الرأي، ثم أدمجها ضمن الفقرة بأسلوب جديد ومهني.
- لا تنسخ عبارات الطالب حرفيًا، بل أعد صياغتها ووسّعها داخل التحليل.
STU;
        }

        return <<<USR
IMPORTANT: Output MUST be JSON only with no extra text outside JSON.

الموضوع الأصلي للمهمة (Task Title):
{$taskTitle}

سياق وتعليمات المهمة (Task Prompt):
{$taskPrompt}

نص التعليق الذي سيُردّ عليه:
{$commentText}

نوع زاوية الرد المطلوب (موافقة / اختلاف / سؤال / توضيح / اقتراح / إضافة):
{$replyTypeLabel}

تعليمات إضافية من المصمم إن وُجدت:
{$replyInstructions}

نبرة الرد المطلوبة: {$tone}
الجمهور المستهدف: {$audience}
{$studentAnswerSection}

تعليمات إلزامية لصياغة محتوى الحقل "content":
1. قبل كتابة الرد، حلّل تعليق الزميل بدقة، واربطه بسياق المهمة وتعليماتها ومتطلبات الأداء.
2. كوّن رأيًا واضحًا وعميقًا حول مدى فهم المهمة وجودة تنفيذها، ثم استخدم هذا الرأي في صياغة الفقرة.
3. طبّق أسلوب "السندويتش" في التغذية الراجعة داخل فقرة واحدة متصلة:
   - بداية الفقرة: شكر وثناء عام على أداء المهمة وجودة المحاولة (بصيغة غير موجّهة مباشرة، مثل: "يُلحظ في هذا التناول جهد واضح في...").
   - منتصف الفقرة: إبراز نقاط القوة في التعليق، مثل دقة الربط بالمراجع، وضوح الفكرة، عمق التأمل، أو جودة الأمثلة.
   - نهاية الفقرة: الإشارة بلطف ووضوح إلى فرص التطوير أو التحسين (مثل توسيع مثال، توضيح مفهوم، ربط أوثق بالمهمة، تعميق الاستناد إلى الأدب التربوي...).
4. ناقش "الطرح" نفسه لا صاحب التعليق؛ تجنّب المخاطبة المباشرة أو ضمير المخاطب، ولا تستخدم عبارات: "زميلي، زميلتي، معلم، معلمة"، ولا تعبيرات مثل "أشكرك" أو "أود أن أقول لك".
5. اجعل المخرج النهائي في الحقل "content" فقرة واحدة مترابطة وواضحة فقط:
   - يمكن أن تحتوي على أكثر من جملة، لكن بدون أسطر جديدة أو فواصل فقرة أو تعداد نقطي أو نجوم أو عناوين فرعية.
   - لا تستخدم أسلوب السؤال والجواب، بل تحليل وتعليق تأملي متصل على التعليق الأصلي.
6. إذا كانت هناك ملاحظة خاصة من الطالب، أدمجها ضمن التحليل لتفرد الرد، دون الإشارة صراحةً إلى أنها قادمة من الطالب.
7. التزم بالنبرة المحددة (tone) وبالجمهور المستهدف (audience) ولكن دون توجيه خطاب مباشر لأفراد محددين.

صيغة الإخراج المطلوبة (JSON واحد فقط):
- "title": عنوان قصير ومعبر للتعليق (مثلاً: "تقدير للمحاولة مع اقتراح لتعميق الربط بالمهمة").
- "content": الفقرة الواحدة الكاملة التي تطبّق ما سبق.
- "tags": مصفوفة من 3 إلى 6 وسوم نصية قصيرة تعبّر عن طبيعة الرد، مثل:
  ["تغذية راجعة","تحليل تعليق","تطوير الممارسة","منتدى تعليمي"].

أخرج كائن JSON واحد فقط بهذه البنية دون أي نص إضافي خارج JSON.
USR;
    }
}
