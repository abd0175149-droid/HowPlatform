<?php
declare(strict_types=1);

namespace App\Libraries\PromptMaker;

/**
 * TeacherFeedbackPromptMaker: بناء توجيهات تغذية راجعة موجهة للمعلم الطالب
 */
class TeacherFeedbackPromptMaker extends BasePromptMaker
{
    public function buildSystemPrompt(string $basePrompt, array $payload): string
    {
        if (trim($basePrompt) === '') {
            return <<<SYS
أنت خبير تربوي متخصص في تحليل أعمال المعلمين الطلبة ضمن الدبلوم المهني في التعليم، وفق أحدث الأدبيات التربوية (بعد 2015)، ووفق منظومة أكاديمية الملكة رانيا للإعداد التربوي والمهني + الإطار العام للمناهج الأردنية.

دورك:
- استقبال البرومت/تعليمات المهمة من المستخدم
- تحليل إجابة الطالب والتغذية الراجعة من الزميل بدقة عالية
- توليد تغذية راجعة مهنية وتربوية موجهة للمعلم الطالب باسمه وضمائر المخاطب

احرص دائمًا على ما يلي:
- بدء التغذية الراجعة بشكر المعلم الطالب على جهده ومخاطبته باسمه مرة واحدة فقط في بداية التغذية الراجعة بشكل مباشر وطبيعي (بدون استخدام "عزيزي" أو "عزيزتي" أو أي عناوين أخرى)
- أن يكون الشكر صادقاً ومهنياً ويركز على تقدير الجهد المبذول
- عدم تكرار اسم المعلم الطالب أكثر من مرة واحدة
- استخدام ضمائر المخاطب (أنت، لك، لديك، عملك، إجابتك...) في جميع أجزاء التغذية الراجعة بعد الشكر والمخاطبة الأولى
- إمكانية صياغة نقاط التطوير والتحسين على شكل أسئلة تأملية تشجع المعلم على التفكير والتحليل الذاتي
- الأسئلة التأملية يجب أن تكون مفتوحة وتدعو للتفكير العميق وترتبط بنقاط التحسين المحددة
- عدم استخدام أي نوع من أنواع العناوين في التغذية الراجعة
- تحليل إجابة الطالب والتغذية الراجعة من الزميل بدقة عالية دون تعديل أو تلخيص
- استخدام لغة أكاديمية تربوية واضحة، دافئة، ومركزة على النمو بأسلوب طبيعي ومباشر
- الالتزام التام بجميع القيود التي يحددها المستخدم باعتبارها إلزامية
- الالتزام التام بأن يكون المخرج كائن JSON واحد صالح فقط، بدون أي نص إضافي قبله أو بعده

لا تُنتِج أبدًا أي شيء خارج JSON صالح واحد.
SYS;
        }
        return trim($basePrompt);
    }

    public function buildUserPrompt(array $payload): string
    {
        $val = fn(?string $s): string => $this->cleanValue($s);

        // جلب البيانات الأساسية من payload
        $taskPrompt = $val($payload['task_prompt'] ?? '');
        $studentAnswer = $val($payload['student_answer'] ?? '');
        $peerFeedback = $val($payload['peer_feedback'] ?? '');
        $teacherName = $val($payload['teacher_name'] ?? '');
        
        // الحقول الإضافية (من instant_feedback_v1)
        $feedbackModel = $val($payload['feedback_model'] ?? 'feed_up_back_forward');
        $depthLevel = $val($payload['depth_level'] ?? 'medium');
        $tone = $val($payload['tone'] ?? 'professional');
        $length = (int)($payload['length'] ?? 400);
        $customConstraints = $val($payload['custom_constraints'] ?? '');
        
        // محاور التركيز (chips)
        $focusPoints = is_array($payload['focus_points'] ?? null)
            ? $payload['focus_points']
            : [];

        // التحقق من وجود الحقول المطلوبة
        if ($taskPrompt === '' || $studentAnswer === '' || $peerFeedback === '' || $teacherName === '') {
            $missing = [];
            if ($taskPrompt === '') $missing[] = 'task_prompt';
            if ($studentAnswer === '') $missing[] = 'student_answer';
            if ($peerFeedback === '') $missing[] = 'peer_feedback';
            if ($teacherName === '') $missing[] = 'teacher_name';
            
            return <<<USR
IMPORTANT: Output MUST be JSON only with no extra text outside JSON.
Return exactly ONE valid JSON object with the following key:
- "feedback": رسالة خطأ تشير إلى أن الحقول التالية ناقصة: {$this->arrayToText($missing)}.

يرجى التأكد من إدخال جميع الحقول المطلوبة.
USR;
        }

        // تعريف نماذج التغذية الراجعة
        $feedbackModels = [
            'feed_up_back_forward' => [
                'label' => 'Feed Up – Feed Back – Feed Forward',
                'description' => <<<MODEL
نموذج ثلاثي الأبعاد:
- Feed Up (ما قبل): تحديد الأهداف والتوقعات الواضحة (ماذا نريد تحقيقه؟)
- Feed Back (الحاضر): تقييم الأداء الحالي بناءً على المعايير (أين أنت الآن؟)
- Feed Forward (ما بعد): اقتراحات للخطوات القادمة والتحسينات (إلى أين تذهب بعد ذلك؟)
MODEL
            ],
            'sbi' => [
                'label' => 'SBI (Situation – Behavior – Impact)',
                'description' => <<<MODEL
نموذج بناء على ثلاث عناصر:
- Situation (الموقف): وصف السياق والموقف الذي حدث فيه السلوك
- Behavior (السلوك): وصف السلوك أو الإجراء الملاحظ بشكل موضوعي
- Impact (التأثير): شرح التأثير والنتائج المترتبة على هذا السلوك
MODEL
            ],
            'sandwich' => [
                'label' => 'Sandwich Feedback (Praise – Critique – Suggestion)',
                'description' => <<<MODEL
نموذج الساندويتش ثلاثي الطبقات:
- Praise (المديح): بدء بتعزيز الإيجابيات ونقاط القوة
- Critique (النقد البناء): تقديم نقاط التحسين والتحديات بشكل بنّاء
- Suggestion (الاقتراح): إنهاء باقتراحات عملية وواضحة للتحسين
MODEL
            ],
            'crc' => [
                'label' => 'CRC (Comment – Recommendation – Comment)',
                'description' => <<<MODEL
نموذج تعليق-توصية-تعليق:
- Comment (التعليق الأول): ملاحظات ومراجعة عامة للعمل
- Recommendation (التوصية): توصيات محددة وواضحة للتحسين
- Comment (التعليق النهائي): تعليقات ختامية داعمة ومشجعة
MODEL
            ]
        ];

        $selectedModel = $feedbackModels[$feedbackModel] ?? $feedbackModels['feed_up_back_forward'];

        // تعريف محاور التركيز
        $focusPointsMap = [
            'objectives_activities_link' => 'الترابط بين الأهداف والأنشطة: تحليل مدى ارتباط الأنشطة بالأهداف المحددة',
            'procedures_outcomes_alignment' => 'ملاءمة الإجراءات للنتاجات: تقييم مدى توافق الإجراءات مع النتاجات المتوقعة',
            'roles_integration' => 'تكامل الأدوار (المعلم/الطالب): تحليل توزيع الأدوار وتكاملها',
            'strategies_implementation' => 'سلاسة توظيف الاستراتيجيات: تقييم فعالية واستخدام الاستراتيجيات',
            'assessment_tools_quality' => 'جودة أدوات التقويم: تحليل جودة أدوات التقويم ودرجتها في قياس النتاجات',
            'integration_horizontal_vertical' => 'قوة التكامل الأفقي والرأسي: تقييم التكامل مع المواد الأخرى (أفقي) والمستويات (رأسي)',
            'diploma_standards_compliance' => 'التوافق مع معايير الدبلوم المهني: تقييم مدى توافق الخطة مع معايير الدبلوم المهني للتعليم'
        ];

        $selectedFocusPoints = [];
        foreach ($focusPoints as $point) {
            if (isset($focusPointsMap[$point])) {
                $selectedFocusPoints[] = $focusPointsMap[$point];
            }
        }

        // تعريف درجات التفصيل
        $depthLevels = [
            'brief' => [
                'label' => 'مختصر',
                'description' => 'تحليل موجز يركز على النقاط الرئيسية فقط (حوالي 200-300 كلمة)',
                'wordCount' => '250'
            ],
            'medium' => [
                'label' => 'متوسط',
                'description' => 'تحليل متوازن يغطي النقاط الرئيسية مع بعض التفاصيل (حوالي 400-600 كلمة)',
                'wordCount' => '500'
            ],
            'detailed' => [
                'label' => 'تفصيلي جداً',
                'description' => 'تحليل شامل وعميق يغطي جميع الجوانب مع أمثلة وتفاصيل (حوالي 800-1200 كلمة)',
                'wordCount' => '1000'
            ]
        ];

        $selectedDepth = $depthLevels[$depthLevel] ?? $depthLevels['medium'];
        if ($length === 400) {
            $length = (int)$selectedDepth['wordCount'];
        }

        // تعريف النبرات
        $tones = [
            'formal' => [
                'label' => 'رسمية',
                'description' => 'استخدم لغة رسمية وأكاديمية مع الحفاظ على الاحترام المهني'
            ],
            'warm' => [
                'label' => 'دافئة',
                'description' => 'استخدم لغة دافئة ومشجعة مع الحفاظ على الطابع المهني'
            ],
            'constructive' => [
                'label' => 'بنائية',
                'description' => 'ركز على البناء والتحسين مع تقديم اقتراحات عملية واضحة'
            ],
            'professional' => [
                'label' => 'مهنية',
                'description' => 'استخدم لغة مهنية متوازنة تجمع بين الدقة والوضوح'
            ]
        ];

        $selectedTone = $tones[$tone] ?? $tones['professional'];

        // حساب نطاق الكلمات
        $lengthMin = max(0, $length - 50);
        $lengthMax = $length + 50;

        // === بناء Core Prompt Section ===
        $corePromptSection = <<<CORE

=== الجزء الأول: الدور والتحليل المطلوب (Core Prompt) ===

دورك هو خبير تربوي متخصص في تحليل أعمال المعلمين الطلبة ضمن الدبلوم المهني في التعليم، وفق أحدث الأدبيات التربوية (بعد 2015)، ووفق منظومة أكاديمية الملكة رانيا للإعداد التربوي والمهني + الإطار العام للمناهج الأردنية.

أنت تستقبل:
1. البرومت/تعليمات المهمة التي قدمها المعلم الطالب
2. إجابة الطالب على المهمة
3. التغذية الراجعة التي قدمها زميل الطالب

وتقوم بما يلي:

1. تحليل إجابة الطالب بدقة عالية واستخراج:
   - نقاط القوة في الإجابة
   - نقاط الضعف أو التحسين
   - مدى الالتزام بالبرومت/تعليمات المهمة
   - جودة المحتوى والتفكير
   - الوضوح والتنظيم

2. تحليل التغذية الراجعة من الزميل واستخراج:
   - نقاط القوة التي أشار إليها الزميل
   - نقاط التحسين التي اقترحها الزميل
   - مدى دقة وموضوعية التغذية الراجعة
   - أي تعليقات أو ملاحظات إضافية

3. توليد تغذية راجعة مهنية وتربوية موجهة للمعلم الطالب {$teacherName}:
   - يجب أن تبدأ التغذية الراجعة بشكر المعلم الطالب "{$teacherName}" على جهده ومخاطبته باسمه بشكل مباشر وطبيعي (بدون استخدام "عزيزي" أو "عزيزتي" أو أي عناوين أخرى)
   - يجب أن يكون الشكر صادقاً ومهنياً ويركز على تقدير الجهد المبذول
   - يجب استخدام ضمائر المخاطب (أنت، لك، لديك، عملك، إجابتك، تحليلك...) في جميع أجزاء التغذية الراجعة بعد الشكر والمخاطبة الأولى
   - يجب أن تكون التغذية الراجعة بناءة وتربوية ومركزة على النمو
   - يمكنك صياغة نقاط التطوير والتحسين على شكل أسئلة تأملية تشجع المعلم على التفكير والتحليل الذاتي
   - الأسئلة التأملية يجب أن تكون مفتوحة وتدعو للتفكير العميق وترتبط بنقاط التحسين المحددة
   - يجب أن تربط بين إجابة الطالب والتغذية الراجعة من الزميل
   - يجب أن يكون الأسلوب طبيعياً ومباشراً دون تكلف أو رسمية مفرطة

4. استخدام لغة أكاديمية تربوية واضحة، دافئة، ومركزة على النمو.

5. كتابة التغذية الراجعة على شكل فقرات مترابطة وسلسة دون استخدام عناوين فرعية أو رموز خاصة أو قوائم نقطية.

CORE;

        // === بناء Task Instructions Section ===
        $taskInstructionsSection = <<<TASK

=== الجزء الثاني: تفاصيل المهمة (Task Instructions Block) ===

البرومت/تعليمات المهمة:

{$taskPrompt}

=== إجابة الطالب ===

{$studentAnswer}

=== التغذية الراجعة من الزميل ===

{$peerFeedback}

TASK;

        // === بناء User Constraints Section ===
        $focusPointsSection = '';
        if (!empty($selectedFocusPoints)) {
            $focusList = implode("\n- ", $selectedFocusPoints);
            $focusPointsSection = <<<FOCUS

نقاط التركيز الأساسية:
- {$focusList}

FOCUS;
        }

        $customConstraintsSection = '';
        if ($customConstraints !== '') {
            $customConstraintsSection = <<<CUSTOM

قيود خاصة إضافية:
{$customConstraints}

CUSTOM;
        }

        $userConstraintsSection = <<<CONSTRAINTS

=== الجزء الثالث: إدخالات المستخدم كقيود إلزامية (User Constraints Block) ===

يجب الالتزام التام بالقيود التالية التي حدّدها المستخدم:

نموذج التغذية الراجعة المطلوب:

{$selectedModel['label']}

{$selectedModel['description']}

(يحظر استخدام أي نموذج آخر مهما كانت الظروف)

{$focusPointsSection}درجة العمق المطلوبة:

{$selectedDepth['label']} - {$selectedDepth['description']}

نبرة الكتابة:

{$selectedTone['label']} - {$selectedTone['description']}

الطول التقريبي للإجابة:

حوالي {$length} كلمة (يمكن أن يتراوح بين {$lengthMin} و {$lengthMax} كلمة)

{$customConstraintsSection}
CONSTRAINTS;

        // === بناء تعليمات بناء التغذية الراجعة ===
        return <<<USR
IMPORTANT: Output MUST be JSON only with no extra text outside JSON.
Return exactly ONE valid JSON object with the following key:
- "feedback": التغذية الراجعة الموجهة للمعلم الطالب كسلسلة نصية واحدة.

{$corePromptSection}

{$taskInstructionsSection}

{$userConstraintsSection}

=== تعليمات إلزامية لبناء محتوى "feedback" ===

1. **الالتزام بالنموذج المختار ({$selectedModel['label']}):**
   - يجب استخدام هذا النموذج حصراً دون أي انحراف
   - لا يجوز الخلط بين النماذج أو استخدام نموذج آخر
   - يجب تطبيق بنية النموذج بدقة كما هو موضح أعلاه

2. **مخاطبة المعلم الطالب والشكر (مهم جداً):**
   - يجب أن تبدأ التغذية الراجعة بشكر المعلم الطالب "{$teacherName}" على جهده ومخاطبته باسمه مرة واحدة فقط في بداية النص بشكل مباشر وطبيعي
   - يجب أن يكون الشكر صادقاً ومهنياً ويركز على تقدير الجهد المبذول في إعداد المهمة وتحليلها
   - لا تستخدم "عزيزي" أو "عزيزتي" أو أي عناوين أخرى عند مخاطبة المعلم الطالب
   - لا تكرر اسم المعلم الطالب أكثر من مرة واحدة في بداية التغذية الراجعة
   - يجب استخدام ضمائر المخاطب (أنت، لك، لديك، عملك، إجابتك، تحليلك، تقييمك...) في جميع أجزاء التغذية الراجعة بعد الشكر والمخاطبة الأولى
   - لا تستخدم ضمير الغائب (هو، له، عمله...) إلا عند الضرورة القصوى
   - يجب أن يكون أسلوب الخطاب طبيعياً ومباشراً وموجهاً للمعلم الطالب دون تكلف

3. **تحليل إجابة الطالب:**
   - حلّل إجابة الطالب بدقة عالية
   - استخرج نقاط القوة والضعف
   - ركّز على مدى الالتزام بالبرومت/تعليمات المهمة
   - قيّم جودة المحتوى والتفكير والوضوح والتنظيم
   - اربط التحليل بالبرومت/تعليمات المهمة

4. **تحليل التغذية الراجعة من الزميل:**
   - حلّل التغذية الراجعة من الزميل بدقة
   - استخرج نقاط القوة والتحسين التي أشار إليها الزميل
   - قيّم مدى دقة وموضوعية التغذية الراجعة
   - اربط بين التغذية الراجعة من الزميل وإجابة الطالب
   - يمكنك صياغة نقاط التحسين المذكورة في التغذية الراجعة من الزميل على شكل أسئلة تأملية تشجع المعلم على التفكير العميق

5. **درجة العمق ({$selectedDepth['label']}):**
   - يجب أن يكون التحليل بمستوى العمق المحدد: {$selectedDepth['description']}
   - التزم بالطول المحدد: حوالي {$length} كلمة

6. **النبرة ({$selectedTone['label']}):**
   - استخدم النبرة المحددة: {$selectedTone['description']}
   - مع الحفاظ على مخاطبة المعلم الطالب باسمه وضمائر المخاطب

7. **نقاط التركيز:**
   - إذا تم تحديد نقاط تركيز، يجب أن تركز التغذية الراجعة عليها بشكل واضح
   - اربط كل نقطة في التغذية الراجعة بنقطة تركيز محددة

8. **بناء التغذية الراجعة:**
   - ابدأ بشكر المعلم الطالب "{$teacherName}" على جهده ومخاطبته باسمه مرة واحدة فقط في بداية التغذية الراجعة بشكل مباشر وطبيعي (بدون "عزيزي" أو "عزيزتي" أو أي عناوين)
   - يجب أن يكون الشكر صادقاً ومهنياً ويركز على تقدير الجهد المبذول
   - لا تكرر اسم المعلم الطالب أكثر من مرة واحدة
   - اربط بين تحليل إجابة الطالب والتغذية الراجعة من الزميل
   - قدم تغذية راجعة بناءة وتربوية ومركزة على النمو بأسلوب طبيعي ومباشر
   - يمكنك صياغة نقاط التطوير والتحسين على شكل أسئلة تأملية تشجع المعلم على التفكير والتحليل الذاتي
   - الأسئلة التأملية يجب أن تكون مفتوحة وتدعو للتفكير العميق وترتبط بنقاط التحسين المحددة
   - استخدم ضمائر المخاطب في جميع أجزاء التغذية الراجعة بعد الشكر والمخاطبة الأولى
   - اكتب على شكل فقرات مترابطة وسلسة بأسلوب طبيعي دون أي عناوين أو رموز خاصة أو قوائم نقطية

9. **القيود الإضافية:**
   - الالتزام التام بأي قيود إضافية محددة من المستخدم
   - هذه القيود إلزامية ولا يمكن تجاهلها

10. **التنسيق والبنية:**
    - اكتب التغذية الراجعة على شكل فقرات مترابطة وسلسة بأسلوب طبيعي
    - لا تستخدم أي نوع من أنواع العناوين (###، ##، #، أو أي عناوين نصية) في التغذية الراجعة
