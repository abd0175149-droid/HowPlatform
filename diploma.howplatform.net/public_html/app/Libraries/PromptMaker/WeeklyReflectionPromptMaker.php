<?php
declare(strict_types=1);

namespace App\Libraries\PromptMaker;

/**
 * WeeklyReflectionPromptMaker: بناء توجيهات كتابة التأمل الأسبوعي باستخدام دورة جيبس
 */
class WeeklyReflectionPromptMaker extends BasePromptMaker
{
    public function buildSystemPrompt(string $basePrompt, array $payload): string
    {
        if (trim($basePrompt) === '') {
            return <<<SYS
أنت خبير في كتابة تأملات أسبوعية مهنية احترافية لمعلمي ومعلمات الدبلوم المهني في التعليم باستخدام دورة جيبس للكتابة الأكاديمية التأملية (Gibbs' Reflective Cycle).
مهمتك إنتاج تأملات عميقة ومنظمة وفق مراحل دورة جيبس الست، تراعي تخصص المعلم وسياق المهمة والموقف المقدم، وتقدّم قيمة مهنية حقيقية.
احرص دائمًا على ما يلي:
- الكتابة بأسلوب أكاديمي مهني، واضح، متماسك، وتأملي موجّه لمعلم/معلمة.
- الالتزام التام بمراحل دورة جيبس الست بالترتيب المحدد.
- تجنّب النسخ الحرفي من نص السؤال أو من ملاحظات المستخدم، وأعد صياغة الأفكار بلغة أكاديمية جديدة مع الحفاظ على المعنى.
- عدم ذكر كونك نموذجًا لغويًا أو نظامًا ذكيًا؛ تحدّث بصوت معلم محترف يشارك تأملاته.
- الالتزام التام بأن يكون المخرج كائن JSON واحد صالح فقط، بدون أي نص إضافي قبله أو بعده أو تعليقات أو شرح خارجي.

لا تُنتِج أبدًا أي شيء خارج JSON صالح واحد.
SYS;
        }
        return trim($basePrompt);
    }

    public function buildUserPrompt(array $payload): string
    {
        $val = fn(?string $s): string => $this->cleanValue($s);

        // جلب البيانات من payload
        $taskTitle = $val($payload['task_title'] ?? '');
        $taskPrompt = $val($payload['task_prompt'] ?? '');
        $teacherSpecialty = $val($payload['teacher_specialty'] ?? '');
        $practiceSituation = $val($payload['practice_situation'] ?? '');
        $wordCount = (int)($payload['word_count'] ?? 500); // افتراضي 500 كلمة

        // بناء قسم التخصص إن وُجد
        $specialtySection = '';
        if ($teacherSpecialty !== '') {
            $specialtySection = <<<SPEC

تخصص المعلم: {$teacherSpecialty}
يجب أن يكون التأمل مخصصًا ومتعلقًا بتخصص المعلم هذا، مع ربط جميع المراحل بتخصصه بشكل واضح.
SPEC;
        }

        // بناء قسم الموقف من الممارسة إن وُجد
        $situationSection = '';
        if ($practiceSituation !== '') {
            $situationSection = <<<SIT

موقف من الممارسة (يجب استخدامه كأساس للتأمل):
{$practiceSituation}

تعليمات إلزامية حول الموقف:
- استخدم هذا الموقف كأساس لجميع مراحل دورة جيبس.
- اربط كل مرحلة من المراحل الست بهذا الموقف بشكل واضح ومباشر.
- لا تنسخ عبارات المستخدم حرفيًا؛ أعد صياغتها بأسلوب أكاديمي مهني.
SIT;
        }

        return <<<USR
IMPORTANT: Output MUST be JSON only with no extra text outside JSON.
Return exactly ONE valid JSON object with the following keys:
- "content": التأمل الكامل وفق دورة جيبس (فقرات مترابطة بدون عناوين فرعية)
- "references": قائمة المراجع (مصفوفة من 1 إلى 2 مراجع بحد أقصى، بصيغة MLA)

بيانات المهمة:
- عنوان المهمة: {$taskTitle}
- وصف المهمة/التوجيهات (Task Prompt): {$taskPrompt}
{$specialtySection}
{$situationSection}

تعليمات إلزامية لبناء التأمل وفق دورة جيبس (نص متكامل واحد):

يجب أن يحتوي النص على جميع مراحل دورة جيبس الست بشكل متكامل ومترابط، بدون عناوين فرعية أو تقسيمات واضحة. اكتب نصًا واحدًا متدفقًا يغطي جميع المراحل بالترتيب التالي:

1. **الوصف (Description)** - ابدأ بوصف تفصيلي وموضوعي للموقف أو التجربة. أجب على: ماذا حدث؟ متى؟ أين؟ من كان حاضرًا؟ ماذا فعلت أنا؟ ماذا فعل الآخرون؟ إذا وُجد موقف من الممارسة، استخدمه كأساس للوصف.

2. **المشاعر (Feelings)** - انتقل بسلاسة لوصف مشاعرك وأفكارك في ذلك الوقت. أجب على: ما الذي شعرت به؟ ما الذي فكرت فيه؟ كيف كان رد فعلك العاطفي؟ كن صادقًا وواضحًا في وصف المشاعر.

3. **التقييم (Evaluation)** - قيّم ما كان جيدًا وما كان سيئًا في التجربة. أجب على: ما الذي سار بشكل جيد؟ ما الذي لم يسِر بشكل جيد؟ ما الذي كان مفيدًا؟ ما الذي كان غير مفيد؟ قدم تقييمًا متوازنًا.

4. **التحليل (Analysis)** - حلّل الموقف بعمق لفهم ما حدث ولماذا. أجب على: ما الذي يمكن أن نستنتجه من هذا الموقف؟ ما هي العوامل التي أثرت على النتيجة؟ ما هي المعرفة النظرية أو الممارسات المهنية ذات الصلة؟ اربط التحليل بالمعرفة النظرية والممارسات المهنية في مجال التخصص ({$teacherSpecialty}).

5. **الاستنتاج (Conclusion)** - استنتج ما تعلمته من هذه التجربة. أجب على: ما الذي تعلمته؟ ما الذي كان يمكن أن أفعله بشكل مختلف؟ ما هي الدروس المستفادة؟

6. **خطة العمل (Action Plan)** - حدد ما ستفعله بشكل مختلف في المستقبل. أجب على: إذا واجهت موقفًا مشابهًا، ماذا سأفعل؟ ما هي الخطوات المحددة التي سأتخذها؟

تعليمات عامة:
- يجب أن يكون النص مكونًا من فقرات مترابطة (عدة فقرات)، وليس فقرة واحدة.
- يجب الانتقال بين المراحل بسلاسة وطبيعية، مع ربط كل مرحلة بالتي تليها.
- يجب ربط جميع المراحل بموضوع المهمة وتخصص المعلم ({$teacherSpecialty}).
- استخدم أسلوبًا أكاديميًا مهنيًا في جميع أنحاء النص.
- تجنّب استخدام التعداد النقطي أو الرقمي أو العناوين الفرعية داخل النص؛ استخدم فقرات مترابطة فقط.
- يجب أن يكون التأمل مخصصًا لطالب وفقًا لتخصصه وأي تعليمات يقدمها في النموذج.

التوثيق والاقتباسات (إلزامي):
- يجب تضمين اقتباسات غير حرفية (paraphrasing) من مراجع مناسبة تدعم السياق.
- استخدم مرجعًا واحدًا إلى مرجعين بحد أقصى (1-2 مراجع فقط).
- يجب أن تكون المراجع مناسبة للسياق وتدعم النقاط المطروحة في التأمل.
- إذا وُجدت مراجع في التوجيه الخاص بالمهمة (task_prompt)، استخدمها أو استخدم مراجع مشابهة مناسبة.

متطلبات المراجع (إلزامي):
- يجب أن تكون المراجع عربية (مكتوبة باللغة العربية أو مترجمة للعربية).
- يجب أن تكون المراجع حديثة: من بعد عام 2015 فما فوق (2015, 2016, 2017... حتى السنة الحالية).
- يجب أن تكون المراجع حقيقية وموثوقة (من مصادر أكاديمية، مجلات علمية، كتب، أو مواقع موثوقة).
- يجب أن تكون المراجع ذات صلة مباشرة بموضوع التأمل وتخصص المعلم ({$teacherSpecialty}).
- لا تخترع مراجع أو تستخدم مراجع وهمية. استخدم فقط مراجع حقيقية وموجودة فعليًا.

نظام التوثيق (MLA):
- في المتن: (اسم المؤلف سنة النشر) أو (اسم المؤلف سنة النشر، رقم الصفحة) إذا كان متوفرًا
- مثال: (الخالدي 2020) أو (الخالدي 2020، 45)
- في قائمة المراجع: استخدم الصيغة الكاملة لـ MLA بالعربية
- مثال للمقال: الخالدي، أحمد. "عنوان المقال." مجلة التربية والتعليم، المجلد 15، العدد 3، 2020، ص 45-60.
- مثال للكتاب: السعدي، محمد. عنوان الكتاب. دار النشر، 2018.
- يجب أن تكون الاقتباسات غير حرفية (paraphrasing) وليست اقتباسات حرفية.
- قائمة المراجع لا تُحسب ضمن عدد الكلمات المطلوب.

الالتزام بعدد الكلمات (إلزامي):
- العدد المطلوب: {$wordCount} كلمة بالضبط.
- الهامش المسموح: ±10% (أي من {$this->calculateMinWords($wordCount)} إلى {$this->calculateMaxWords($wordCount)} كلمة).
- يجب أن تحسب عدد الكلمات بدقة وتضمن أن النص النهائي يقع ضمن هذا النطاق.
- لا تتجاوز الحد الأدنى أو الحد الأقصى بأي حال من الأحوال.

تذكير أخير:
- أعد التأمل بصيغة JSON فقط، بلا أي شرح أو تعليقات خارجية.
- أي خروج عن البنية المحددة (content, references) أو إضافة نص خارج JSON يُعتبر مخالفة للتعليمات.
- يجب أن يكون "content" نصًا متكاملًا مكونًا من فقرات مترابطة يغطي جميع مراحل دورة جيبس الست بدون عناوين فرعية.
- يجب أن يكون عدد الكلمات في "content" بالضبط بين {$this->calculateMinWords($wordCount)} و {$this->calculateMaxWords($wordCount)} كلمة (الهدف: {$wordCount} كلمة مع هامش ±10%).
- يجب أن يحتوي "references" على مصفوفة من 1 إلى 2 مراجع بحد أقصى، كل مرجع بصيغة MLA كاملة.
- مثال لبنية JSON المطلوبة:
{
  "content": "النص الكامل للتأمل...",
  "references": [
    "Smith, John. \"عنوان المقال.\" اسم المجلة، المجلد، العدد، سنة النشر، الصفحات.",
    "Doe, Jane. عنوان الكتاب. الناشر، سنة النشر."
  ]
}
USR;
    }

    /**
     * حساب الحد الأدنى للكلمات (الهدف - 10%)
     */
    private function calculateMinWords(int $target): int
    {
        return (int) floor($target * 0.9);
    }

    /**
     * حساب الحد الأقصى للكلمات (الهدف + 10%)
     */
    private function calculateMaxWords(int $target): int
    {
        return (int) ceil($target * 1.1);
    }
}

