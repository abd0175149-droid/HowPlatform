<?php

declare(strict_types=1);

namespace App\Libraries\PromptMaker;

/**
 * InquiryResearchPromptMaker
 * بناء توجيهات أداة مخطط البحث الاستقصائي (Action Research) الكامل
 * تُنتج الأقسام الستة + الملاحق وفق النموذج المعتمد في برنامج الدبلوم.
 */
class InquiryResearchPromptMaker extends BasePromptMaker
{
    /**
     * System Prompt: تعريف دور الذكاء الاصطناعي
     */
    public function buildSystemPrompt(string $basePrompt, array $payload): string
    {
        if (trim($basePrompt) !== '') {
            return trim($basePrompt);
        }

        return <<<SYS
أنت خبير تربوي متخصص في البحث الإجرائي (Action Research) ومساعدة المعلمين على كتابة بحوث استقصائية صفية أكاديمية محكمة.
تكتب بأسلوب أكاديمي رصين باللغة العربية الفصحى، مع الالتزام الدقيق بعدد الكلمات المحدد لكل قسم.
أرجع JSON صالح فقط ولا تكتب أي شيء آخر خارج JSON.
SYS;
    }

    /**
     * User Prompt: بناء التوجيه الكامل للبحث الاستقصائي
     */
    public function buildUserPrompt(array $payload): string
    {
        $val  = fn(?string $s): string => $this->cleanValue($s);
        $join = fn($arr): string       => $this->arrayToText($arr);

        // ── الحقول الأساسية ──
        $researchQuestion     = $val($payload['research_question']     ?? '');
        $subjectName          = $val($payload['subject_name']          ?? '');
        $lessonTitle          = $val($payload['lesson_title']          ?? '');
        $learningOutcomes     = $val($payload['learning_outcomes']     ?? '');

        // ── سياق المدرسة (جديد) ──
        $studentGender        = $val($payload['student_gender']        ?? '');
        $gradeLevel           = $val($payload['grade_level']           ?? '');
        $schoolLevel          = $val($payload['school_level']          ?? '');
        $schoolLocation       = $val($payload['school_location']       ?? '');

        // ── الاستراتيجيات ──
        $teachingStrategies   = $join($payload['teaching_strategies']  ?? []);
        $assessmentStrategies = $join($payload['assessment_strategies'] ?? []);

        // ── ترجمة جنس الطلبة ──
        $genderLabel = match ($studentGender) {
            'male'   => 'ذكور',
            'female' => 'إناث',
            'mixed'  => 'مختلط (ذكور وإناث)',
            default  => 'غير محدد',
        };

        // ── ترجمة مستوى المدرسة ──
        $schoolLevelLabel = match ($schoolLevel) {
            'primary'      => 'ابتدائية',
            'intermediate' => 'إعدادية',
            'secondary'    => 'ثانوية',
            default        => $schoolLevel,
        };

        // ── ملاحظة الاستراتيجيات للجدول ──
        $tableNote = '';
        if (!empty($teachingStrategies)) {
            $tableNote .= "- استراتيجيات التدريس التي يُفضّلها المعلم: {$teachingStrategies}\n";
        }
        if (!empty($assessmentStrategies)) {
            $tableNote .= "- أدوات التقويم التي يُفضّلها المعلم: {$assessmentStrategies}\n";
        }

        $prompt = <<<USR
IMPORTANT: Output MUST be valid JSON only — no text outside JSON, no markdown fences.

أنا معلم في برنامج الدبلوم وأريد مساعدتك في كتابة مخطط بحث استقصائي (إجرائي) متكامل يشمل ستة أقسام رئيسية + الملاحق.

## بيانات البحث الأساسية
- سؤال البحث الاستقصائي: {$researchQuestion}
- المادة الدراسية: {$subjectName}
- عنوان الدرس / الآلية محور البحث: {$lessonTitle}
- نتاجات التعلم المدخلة من المعلم: {$learningOutcomes}

## سياق المدرسة
- جنس الطلبة: {$genderLabel}
- الصف الدراسي الذي سيجرى عليه البحث: {$gradeLevel}
- مستوى المدرسة: {$schoolLevelLabel}
- موقع المدرسة (منطقة / مدينة / قرية): {$schoolLocation}
{$tableNote}

---

## قواعد عامة صارمة — اقرأها قبل الكتابة

1. **سؤال البحث**: يُحظر تغيير سؤال البحث أو إعادة صياغته تحت أي ظرف. استخدمه كما هو حرفياً.

2. **النتاجات**: اقرأ النتاجات المُدخلة بعناية؛ إن كانت صياغتها غير دقيقة أو غير قابلة للقياس، صحّحها داخلياً لتكون SMART واستخدم الصياغة المصحّحة في جميع أقسام البحث دون الإشارة إلى ذلك.

3. **المراجع**:
   - الحد الأدنى 8 مراجع إجمالاً.
   - لا يجوز الاستشهاد بأي مرجع يسبق عام 2018.
   - يُحظر تماماً إضافة مواقع إنترنت عامة أو مصادر غير محكّمة.
   - المراجع الأساسية الإلزامية (يجب أن تكون جميعها حاضرة):
     أ) قراءة الاستقصاء كنهج وممارسة (Reading Inquiry as an Approach and Practice)
     ب) دليل المعلم – صورة الدرس (Teacher's Guide – Lesson Portrait)
     ج) الإطار العام للمنهاج الخاص بمادة المعلم
     د) معايير المعلمين — يُكتب المرجع باسم: أكاديمية الملكة رانيا لتدريب المعلمين. (2024). معايير المعلمين. دون ذكر وزارة التربية والتعليم.
   - أضف 4 مراجع إضافية وفق الترتيب الموضّح في قسم مراجعة الأدب التربوي.
   - اكتب جميع المراجع بصيغة MLA كاملة.

4. **الجدول** (القسم الثالث): يحتوي على 2-3 صفوف تمثّل 2-3 حصص دراسية فعلية، كل صف لحصة واحدة.

5. **الملاحق**: إلزامية:
   - دليل المعلم / الكتاب المدرسي
   - خطط الدروس المُعدّة
   - يمكن إضافة أدوات تقويم استخدمتها (بطاقة ملاحظة، ورقة عمل...) إن ذُكرت في النتائج.

6. **الالتزام بعدد الكلمات**: التزم بالحدود المذكورة لكل قسم بدقة.

7. **الأسلوب**: اكتب بأسلوب أكاديمي رصين بفقرات متكاملة مترابطة تعكس صوت المعلم في المضارع أو المستقبل (أنا المعلم الذي يكتب هذا المخطط).

8. **يُمنع منعاً باتاً** في القسم الثالث: الاختبار القبلي/البعدي، الاستبانات، المقابلات الشخصية.

---

