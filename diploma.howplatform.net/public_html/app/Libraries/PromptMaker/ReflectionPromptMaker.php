<?php
declare(strict_types=1);

namespace App\Libraries\PromptMaker;

/**
 * ReflectionPromptMaker: بناء توجيهات كتابة التأمل
 */
class ReflectionPromptMaker extends BasePromptMaker
{
    public function buildSystemPrompt(string $basePrompt, array $payload): string
    {
        if (trim($basePrompt) === '') {
            return <<<SYS
أنت خبير في كتابة تأملات مهنية احترافية لمعلمي ومعلمات الدبلوم المهني في التعليم.
مهمتك إنتاج تأملات عميقة وتأملية حول موضوع المهمة، تراعي تخصص المعلم وسياق المهمة، وتقدّم قيمة مهنية حقيقية.
احرص دائمًا على ما يلي:
- الكتابة بأسلوب مهني، واضح، متماسك، وتأملي موجّه لمعلم/معلمة.
- تجنّب النسخ الحرفي من نص السؤال أو من ملاحظات المستخدم، وأعد صياغة الأفكار بلغة جديدة مع الحفاظ على المعنى.
- عدم ذكر كونك نموذجًا لغويًا أو نظامًا ذكيًا؛ تحدّث بصوت معلم محترف يشارك تأملاته.
- الالتزام التام بأن يكون المخرج كائن JSON واحد صالح فقط، بدون أي نص إضافي قبله أو بعده أو تعليقات أو شرح خارجي.
- عدم إخراج أي شيفرة أو كائنات JSON إضافية داخل النص، بل كائن JSON واحد فقط على المستوى الأعلى.

لا تُنتِج أبدًا أي شيء خارج JSON صالح واحد.
SYS;
        }
        return trim($basePrompt);
    }

    public function buildUserPrompt(array $payload): string
    {
        $val = fn(?string $s): string => $this->cleanValue($s);

        // جلب البيانات من payload
        $taskTitle        = $val($payload['task_title'] ?? '');
        $taskPrompt       = $val($payload['task_prompt'] ?? '');
        $teacherSpecialty = $val($payload['teacher_specialty'] ?? '');
        $tone             = $val($payload['tone'] ?? 'formal');
        $audience         = $val($payload['audience'] ?? 'teachers');

        // requirements قد يكون array (chips) أو string
        $requirements = is_array($payload['requirements'] ?? null)
            ? $this->arrayToText($payload['requirements'])
            : $val($payload['requirements'] ?? '');

        $initialIdeas = $val($payload['initial_ideas'] ?? '');

        // بناء قسم الأفكار الأولية إن وُجدت
        $initialIdeasSection = '';
        if ($initialIdeas !== '') {
            $initialIdeasSection = <<<IDEAS

أفكار أولية/مبدئية من المستخدم (يجب استخدامها كنواة لبناء التأمل):
{$initialIdeas}

تعليمات إلزامية حول الأفكار الأولية:
- اقرأ هذه الأفكار بعناية، واستخرج منها المحاور الرئيسة والأفكار الجوهرية ونقاط الترابط مع المهمة.
- لا تنسخ عبارات المستخدم حرفيًا؛ أعد صياغتها وعمّقها ضمن التأمل بأسلوب مهني جديد.
- اجعل هذه الأفكار محورًا أساسيًا في بناء التأمل، مع توسيعها وتأطيرها نظريًا بما يناسب سياق المهمة.
IDEAS;
        }

        // بناء قسم التخصص إن وُجد
        $specialtySection = '';
        if ($teacherSpecialty !== '') {
            $specialtySection = <<<SPEC

تخصص المعلم: {$teacherSpecialty}
يجب أن يكون التأمل مخصصًا ومتعلقًا بهذا التخصص، مع ربط الموضوع ومواقف الصف بالتخصص بشكل واضح قدر الإمكان.
SPEC;
        }

        return <<<USR
IMPORTANT: Output MUST be JSON only with no extra text outside JSON.
Return exactly ONE valid JSON object with the following keys:
- "content": التأمل الكامل كسلسلة نصية واحدة تحتوي فقرتين مترابطتين فقط.

بيانات المهمة:
- عنوان المهمة: {$taskTitle}
- وصف المهمة/المتطلبات (Task Prompt): {$taskPrompt}
{$specialtySection}
- الجمهور المستهدف: {$audience}
- النبرة المطلوبة: {$tone}
- عناصر/خيارات يجب تضمينها في التأمل: {$requirements}
{$initialIdeasSection}

تعليمات إلزامية لبناء محتوى "content":
1. حلّل سياق المهمة ومتطلباتها بدقة، ثم اربط بين سياق المهمة والتعليمات الخاصة (النبرة، الجمهور، العناصر المطلوبة) باعتبارها تعليمات إلزامية يجب الالتزام بها دائمًا.
2. إذا وُجدت أفكار أولية من المستخدم، فهِمْها بعمق واستخرج منها المحاور الرئيسة ونقاط الترابط مع المهمة، واستخدمها كنواة لكتابة التأمل مع إعادة الصياغة وعدم النسخ الحرفي.
3. اجعل التأمل مخصصًا لمعلم/معلمة في تخصصه/تخصصها كما هو مذكور في بيانات المهمة إن وُجد، مع ربط الأمثلة الصفّية ومواقف التعلّم بهذا التخصص قدر الإمكان.
4. اجعل المخرج النهائي فقرتين مترابطتين فقط في الحقل "content"، بطول إجمالي يقارب 150 كلمة (يمكن أن يتراوح تقريبًا بين 140 و 170 كلمة) مكتوبة وفق استراتيجية PEEL داخليًا دون ذكرها بالاسم:
   - Point: فكرة رئيسة واضحة مرتبطة مباشرةً بموضوع المهمة أو سؤالها المحوري.
   - Evidence: مثال أو موقف من واقع الخبرة المدرسية في الغرفة الصفية يدعم هذه الفكرة.
   - Explanation: تفسير تحليلي يربط بين المثال والمفاهيم أو القراءات أو المعايير المهنية ذات الصلة.
   - Link: جملة ختامية تربط التأمل مباشرةً بموضوع المهمة أو غايات التعلّم أو تطوّر كفايات المعلم.
5. يجب ربط النص بشكل صريح بموضوع المهمة ومتطلباتها وسياقها، ولكن بدون اعتماد أسلوب سؤال وجواب، بل على شكل نص تأملي/تحليلي متصل.
6. لا تستخدم في "content" أي ترقيم أو تعداد نقطي أو رقمي أو نجوم أو عناوين فرعية أو جداول أو تنسيق Markdown؛ النص يجب أن يكون متصلًا على شكل فقرتين فقط بينهما انتقال طبيعي.
7. تجنّب إدراج أي JSON أو شيفرة أو أقواس برمجية داخل الحقل "content". يجب أن يحتوي "content" على نص عادي فقط (plain text).
8. يجب أن تكون الفقرتان مترابطتين بشكل منطقي وسلس، مع انتقال واضح من عرض الفكرة والمثال إلى التفسير والربط بالغايات المهنية.

تذكير أخير:
- أخرج النتيجة على شكل كائن JSON واحد فقط بالمفتاح "content" كما هو محدد أعلاه، بلا أي شرح أو تعليقات خارجية.
- أي خروج عن هذه البنية أو إضافة نص خارج JSON يُعتبر مخالفة للتعليمات.
USR;
    }
}
