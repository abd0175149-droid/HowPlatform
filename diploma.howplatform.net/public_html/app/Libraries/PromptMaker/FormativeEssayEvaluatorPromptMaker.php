<?php
declare(strict_types=1);

namespace App\Libraries\PromptMaker;

/**
 * FormativeEssayEvaluatorPromptMaker
 * ------------------------------------------------------------------
 * مُقيّم المقالة التأمّلية البنائية (تكويني، بلا درجات) وفق إطار Gibbs.
 * المدخل: essay_text (نصّ المقالة المستخرَج خادمياً من ملف .docx) + teacher_specialty.
 * المخرج المطلوب من النموذج: كائن JSON واحد:
 *   { "report": {4 مجالات × مراحل Gibbs الستّ + overall_suggested_actions}, "annotations": [>=18] }
 *
 * قواعد صارمة:
 *  - whitelist للمفاتيح فقط (لا تسريب run_map/__meta/blobs).
 *  - essay_text يبقى خاماً (دون cleanValue) كي ينسخ النموذج اقتباساته حرفياً.
 *  - anchor_text حرفيّ من essay_text ولا يعبر فاصل فقرة "\n".
 *  - لا يُسجَّل في PromptMakerFactory::$makers (يُحلّ عبر DB prompt_maker_class).
 */
class FormativeEssayEvaluatorPromptMaker extends BasePromptMaker
{
    /** المجالات الأربعة: مفتاح JSON => العنوان العربي. */
    private const DOMAINS = [
        'knowledge_understanding_application' => 'المعرفة والفهم والتطبيق',
        'cognitive_skills'                   => 'المهارات المعرفية (التفكير الناقد والتأمّل)',
        'professional_skills'                => 'المهارات المهنية وأصول التدريس',
        'presentation'                       => 'العرض والتقديم',
    ];

    public function buildSystemPrompt(string $basePrompt, array $payload): string
    {
        // نُعيد system_prompt من قاعدة البيانات كما هو (مرآة InquiryReportEvaluatorPromptMaker).
        return trim($basePrompt);
    }

    public function buildUserPrompt(array $payload): string
    {
        // ── whitelist صارم: المفاتيح المسموح ضمّها فقط ──
        $teacherSpecialty = $this->cleanValue(is_scalar($payload['teacher_specialty'] ?? null) ? (string)$payload['teacher_specialty'] : '');
        $taskTitle        = $this->cleanValue(is_scalar($payload['task_title'] ?? null) ? (string)$payload['task_title'] : '');
        $taskPrompt       = trim((string)($payload['task_prompt'] ?? ''));
        // essay_text يبقى خاماً (verbatim) — لا تنظيف، كي تتطابق الاقتباسات حرفياً.
        $essayText        = (string)($payload['essay_text'] ?? '');

        $specialtyLine = $teacherSpecialty !== '' ? $teacherSpecialty : '(غير محدّد)';
        $taskTitleLine = $taskTitle !== '' ? $taskTitle : '(غير محدّد)';
        $taskCtx       = $taskPrompt !== '' ? $taskPrompt : '(لا يوجد وصف مهمة)';

        // عدد فقرات المقالة (لتوزيع التعليقات على كامل النص فقرةً فقرة)
        $paraCount = count(array_filter(
            array_map('trim', preg_split('/\R/u', $essayText) ?: []),
            static fn($l) => $l !== ''
        ));
        $paraCount = max(1, $paraCount);

        $domainsList = $this->buildDomainsList();
        $jsonStruct  = $this->buildJsonStructure();

        $user = <<<USR
IMPORTANT: Output MUST be a SINGLE valid JSON object only — no extra text, no markdown, no code blocks. Start with { and end with }.

=== الجزء الأول: تخصّص المعلّم (لمواءمة الأمثلة والسياق) ===
{$specialtyLine}

=== الجزء الثاني: عنوان المهمة ===
{$taskTitleLine}

=== الجزء الثالث: سياق/وصف المهمة (اختياري) ===
{$taskCtx}

=== الجزء الرابع: نصّ المقالة التأمّلية للطالب (للتقييم والاقتباس الحرفي) ===
الفقرات مفصولة بسطر جديد، وعدد فقرات المقالة: {$paraCount}. لا تختر اقتباساً (anchor_text) يحتوي على فاصل سطر؛ اختر جملة أو جزء جملة داخل فقرة واحدة.
التوزيع إلزامي وصارم: يجب أن تغطّي التعليقات كامل المقالة من فقرتها الأولى إلى الأخيرة، فلا تخلو أيّ فقرة من تعليق واحد على الأقل (والفقرات الأطول أو الأغنى تأمّلاً تأخذ تعليقين)، ويُمنع تركيز التعليقات في جزء وإهمال باقي الأجزاء.

=== ESSAY START ===
{$essayText}
=== ESSAY END ===

=== الجزء الخامس: المجالات الأربعة (لكل مجال: نقاط قوّة + مجالات تحسين) ===
{$domainsList}

=== الجزء السادس: هيكل JSON المطلوب (التزم به حرفياً) ===
{$jsonStruct}

تذكير نهائي صارم:
1) كائن JSON واحد فقط، بلا أيّ نص خارجه، بلا markdown.
2) تقييم تكويني بنّاء — ممنوع منح أيّ درجة أو رمز تقدير (لا P/GP/M/D/F ولا أرقام).
3) كل anchor_text منسوخ حرفياً من نصّ المقالة أعلاه (verbatim) دون إعادة صياغة أو إضافة تشكيل، وداخل فقرة واحدة (لا يحتوي على سطر جديد).
4) آلية اختيار ذكية وواعية: قيّم المقالة كاملةً تقييماً شاملاً أوّلاً، ثمّ اختر بوعيٍ مواضعَ التعليق (anchor_text) الأكثر دلالةً تأمّلياً في كلّ جزء من المقالة وما ستعلّق به. أنتج من 16 إلى 20 تعليقاً موزّعة على كامل النص وعلى المجالات الأربعة، بحيث تُغطّى كلّ فقرات المقالة ({$paraCount} فقرة) دون إهمال أيّ جزء (فقرة واحدة = تعليق واحد على الأقل)؛ لا تقلّ الصالحة عن 15، وتجنّب تكرار الفكرة نفسها.
5) كل تعليق هامشي = فقرة واحدة متكاملة مترابطة (لا نقاط منفصلة ولا عناوين ولا ترقيم) تنسج منهجية (الموقف – السلوك – الأثر) ثمّ ما يمكن تحسينه في الفقرة، في نصّ قوي عميق يعكس تحليلاً معمّقاً لا سطحياً، ويُمنع منعاً باتّاً اقتباس أو ذكر أيّ جزء من نصّ الفقرة داخل التعليق (anchor_text لتحديد الموضع فقط)، بنبرة بنّاءة محايدة جنسياً.
6) التقييم في «report» عميق ودقيق غير سطحي، مدعوم بأدلّة جوهريّة من صلب النص مع تحليلها، وحقل overall_suggested_actions فقرة شاملة عميقة تلخّص كل إجراءات التطوير، واللغة عربية فصيحة.
USR;

        return $user;
    }

    /** قائمة المجالات الأربعة بصياغة موجّهة. */
    private function buildDomainsList(): string
    {
        $lines = [];
        $i = 1;
        foreach (self::DOMAINS as $key => $label) {
            $lines[] = "{$i}) {$label}  [مفتاح JSON: {$key}]";
            $i++;
        }
        $lines[] = "";
        $lines[] = "لكل مجال اكتب حقلين: نقاط القوّة (strengths) ومجالات التحسين (areas_for_improvement)، تغذيةً راجعةً تكوينيةً بنّاءةً (بلا أيّ درجات) تستلهم تأمّل دورة Gibbs دون ذكر مراحلها صراحةً، مع الالتزام الصارم بما يلي:";
        $lines[] = "• العمق لا السطحيّة: قدّم تقييماً تربوياً دقيقاً وعميقاً يحلّل «لماذا» و«كيف»، لا مجرّد وصف عام أو إعادة سرد لما كتبه المعلّم الطالب؛ تجنّب العبارات الإنشائيّة العامّة والمجاملات المبهمة.";
        $lines[] = "• الأدلّة الجوهريّة: ادعم كل حكم بدليلٍ محدّد من صلب المقالة (إشارة دقيقة أو اقتباس قصير)، ثمّ حلّل الدليل تحليلاً عميقاً: ماذا يكشف عن تفكير المعلّم الطالب وممارسته، وما أثره الفعلي على تعلّم الطلبة — لا تكتفِ بسرد الدليل دون تحليل.";
        $lines[] = "• التفصيل والتوسّع: كل حقل فقرةٌ موسّعةٌ لا تقلّ عن 5–7 جُمَل، محدّدة وعمليّة، غنيّة بالأدلّة.";
        $lines[] = "• في «نقاط القوّة»: اذكر أكثر من نقطة قوّة جوهريّة، كلٌّ بدليلها المحدّد من النص وتحليلٍ عميق لأثرها التربوي.";
        $lines[] = "• في «مجالات التحسين»: قدّمها بأسلوب «الساندويتش» في تقديم التغذية الراجعة عبر ثلاث طبقات متتابعة داخل الفقرة نفسها:";
        $lines[] = "   (1) الطبقة العليا: ابدأ بإقرار إيجابي صادق مستندٍ إلى دليل من النص.";
        $lines[] = "   (2) الحشوة: ثمّ اعرض مجال التحسين المحدّد بعمق مع سببه التربوي ودليله من النص وخطوات عمليّة دقيقة قابلة للتطبيق فوراً.";
        $lines[] = "   (3) الطبقة السفلى: واختم بعبارة تشجيعيّة محفّزة تربط التحسين بنموّه المهني وثقته بقدرته على التطوّر.";
        $lines[] = "• النبرة بنّاءة محترمة محايدة جنسياً، واللغة عربية فصيحة سليمة.";
        return implode("\n", $lines);
    }

    /** الهيكل الإلزامي للمخرجات (مطابق لنموذج «تقرير التغذية الراجعة البنائي»). */
    private function buildJsonStructure(): string
    {
        return <<<'STRUCTURE'
{
  "report": {
    "student_name": "اسم المعلم الطالب إن ورد صراحةً في المقالة، وإلا اتركه فارغاً \"\"",
    "knowledge_understanding_application": {
      "strengths": "نقاط القوّة الجوهريّة — فقرة موسّعة (5–7 جُمَل) بأكثر من نقطة، كلٌّ بدليلٍ محدّد من صلب النص وتحليلٍ عميق لأثرها التربوي (لا سرد سطحي)",
      "areas_for_improvement": "مجالات التحسين بعمق — فقرة موسّعة (5–7 جُمَل) بأسلوب الساندويتش، مدعومة بأدلّة جوهريّة من النص وتحليلٍ دقيق وخطوات عمليّة محدّدة"
    },
    "cognitive_skills":      { "strengths": "...", "areas_for_improvement": "..." },
    "professional_skills":   { "strengths": "...", "areas_for_improvement": "..." },
