      "comment": "فقرة واحدة متكاملة ومترابطة (وليست نقاطاً منفصلة ولا عناوين ولا ترقيم) تُحلّل هذا الجزء بعمق وتنسج منهجية (الموقف – السلوك – الأثر) في سياق واحد سلس: سياق/موقف هذا الجزء، ثمّ ما فعله المعلّم الطالب فيه، ثمّ أثر ذلك على عمق التأمّل وتعلّم الطلبة، وتختم بما يمكن تحسينه في هذه الفقرة عبر اقتراح عملي محدّد — نصّ قوي مترابط عميق يعكس تحليلاً معمّقاً لا رداً سطحياً، ويُمنع اقتباس أو ذكر أيّ جزء من نصّ الفقرة داخل التعليق",
      "domain": "knowledge_understanding_application"
    }
  ]
}
STRUCTURE;
    }
}
