    "overall_suggested_actions": "فقرة عميقة وشاملة (لا تعداد سطحي) تلخّص جميع الإجراءات المُقترحة لتطوير المقالة تطويراً كاملاً ودقيقاً: تجمع أبرز أولويّات التحسين عبر المجالات الأربعة في رؤية متكاملة مترابطة، مع كيفية تنفيذها عملياً، بحيث تُشكّل خارطة طريق واضحة لرفع جودة التأمّل"
