namespace App\Libraries\PromptMaker;

/**
 * CaseIntegrationPromptMaker: بناء توجيهات دمج الحالة
 */
class CaseIntegrationPromptMaker extends BasePromptMaker
{
    public function buildSystemPrompt(string $basePrompt, array $payload): string
    {
        if (trim($basePrompt) === '') {
            return <<<SYS
أنت خبير متخصص في بناء سيناريوهات دمج الحالة التربوية والتعليمية. مهمتك هي تحليل المدخلات الأولية من المعلم الطالب وبناء سيناريو كامل ومناسب لدمج الحالة في سياق تعليمي.

دورك:
- خبير تربوي متخصص في دمج الحالات التعليمية
- تحلل المدخلات الأولية بشكل عميق
- تبني سيناريو تعليمي متكامل
- تربط الموقف بمعايير المعلمين المحددة
- تقدم حلولاً عملية وقابلة للتطبيق

كيفية العمل:
1. فهم المدخلات: اقرأ اسم المعلم، الحالة، ووصف الحالة بعناية
2. بناء السيناريو: أنشئ سيناريو تعليمي كامل يدمج الحالة بشكل طبيعي
3. تحديد العناصر: حدد سبب الدمج، الأنشطة، البيئة، أصحاب العلاقة
4. ربط بالمعايير: ربط الموقف بمعايير المعلمين (بالرمز فقط مثل: 1.1.4، 2.3.1)
   - استخدم قائمة معايير المعلمين الكاملة المتوفرة في رسالة المستخدم
   - اختر فقط المعايير ذات العلاقة الواضحة بالموقف
   - أدرج فقط رموز المعايير (مثل: "1.1.4") بدون أي وصف أو شرح
5. صياغة دقيقة: اكتب إجابة واضحة ومهنية باللغة العربية الفصحى

المخرجات المطلوبة:
- يجب أن تكون المخرجات JSON صالح فقط، بدون أي نص خارجي
- ابدأ مباشرة بـ { وانتهي بـ }
- لا تستخدم markdown code blocks (```json أو ```)
- لا تضع أي شرح أو تعليقات خارج JSON
- جميع الحقول النصية باللغة العربية الفصحى المهنية
- التحليل يجب أن يكون عميقاً وليس سطحياً

في حالة نقص المدخلات الجوهرية، أعد JSON وفق بروتوكول نقص المدخلات المحدد في رسالة المستخدم.
SYS;
        }
        return trim($basePrompt);
    }

    public function buildUserPrompt(array $payload): string
    {
        $val = fn(?string $s): string => $this->cleanValue($s);

        $teacherName = $val($payload['teacher_name'] ?? '');
        $teacherSpecialty = $val($payload['teacher_specialty'] ?? '');
        $case = $val($payload['case'] ?? '');
        $caseDescription = $val($payload['case_description'] ?? '');
        
        // جلب معايير المعلمين (قد تكون من task_prompt أو من payload مباشرة)
        $criteria = [];
        if (isset($payload['criteria']) && is_array($payload['criteria'])) {
            $criteria = $payload['criteria'];
        } elseif (isset($payload['task_prompt'])) {
            // محاولة استخراج المعايير من task_prompt إذا كان JSON
            try {
                $parsed = json_decode($payload['task_prompt'], true);
                if (is_array($parsed) && isset($parsed['criteria']) && is_array($parsed['criteria'])) {
                    $criteria = $parsed['criteria'];
                }
            } catch (\Exception $e) {
                // إذا لم يكن JSON، تجاهل
            }
        }

        // تحويل المعايير إلى نص
        $criteriaText = '';
        if (!empty($criteria)) {
            $criteriaLines = [];
            foreach ($criteria as $criterion) {
                if (is_string($criterion)) {
                    // إذا كان نصاً، حاول استخراج الرمز
                    if (preg_match('/^(\d+\.\d+\.\d+)/', $criterion, $matches)) {
                        $criteriaLines[] = '• ' . $criterion;
                    } else {
                        $criteriaLines[] = '• ' . $criterion;
                    }
                } elseif (is_array($criterion) && isset($criterion['code']) && isset($criterion['description'])) {
                    $criteriaLines[] = '• ' . $criterion['code'] . ': ' . $criterion['description'];
                } elseif (is_array($criterion) && isset($criterion['code'])) {
                    $criteriaLines[] = '• ' . $criterion['code'];
                }
            }
            $criteriaText = implode("\n", $criteriaLines);
        } else {
            // إذا لم تكن هناك معايير محددة، استخدم القائمة الكاملة كمرجع
            $criteriaText = $this->getFullCriteriaList();
        }

        $user = <<<USR
IMPORTANT: Output MUST be JSON only with no extra text outside JSON. Start with { and end with }.

المهمة: بناء سيناريو كامل لدمج حالة تربوية في سياق تعليمي وفق المدخلات الأولية من المعلم الطالب.

المدخلات الأولية:
- اسم المعلم الطالب: {$teacherName}
- تخصص المعلم: {$teacherSpecialty}
- الحالة: {$case}
- وصف الحالة: {$caseDescription}

معايير المعلمين:
{$criteriaText}

ملاحظة مهمة حول المعايير:
- إذا كانت المعايير محددة أعلاه (من task_prompt)، استخدمها فقط واربط الموقف بها
- إذا لم تكن المعايير محددة، استخدم القائمة الكاملة أعلاه كمرجع لاختيار المعايير المناسبة من جميع المعايير المتاحة
- في جميع الأحوال، أدرج فقط رموز المعايير (مثل: "1.1.4") في المصفوفة النهائية

تعليمات العمل خطوة بخطوة:

1. التحقق من المدخلات:
   - تحقق من اكتمال جميع المدخلات (teacher_name, teacher_specialty, case, case_description)
   - إذا كان هناك نقص، أعد JSON وفق بروتوكول نقص المدخلات

2. بناء السيناريو:
   - بناء على المدخلات الأولية، أنشئ سيناريو تعليمي كامل يدمج الحالة بشكل طبيعي
   - السيناريو يجب أن يكون واقعياً وقابلاً للتطبيق
   - يجب أن يوضح كيف يمكن دمج هذه الحالة في العملية التعليمية
   - راعِ تخصص المعلم ({$teacherSpecialty}) عند بناء السيناريو والأنشطة المقترحة
   - يجب أن تكون الأنشطة والحلول مناسبة للتخصص المحدد

3. سبب دمج الحالة (reason_for_integration):
   - اشرح لماذا يتم دمج هذه الحالة في السياق التعليمي
   - وضح الفوائد التعليمية والتربوية من هذا الدمج
   - اذكر الأهداف التعليمية المرجوة من دمج الحالة

4. أنشطة التعلم (activities):
   - اقترح أنشطة تعليمية مناسبة لدمج الحالة
   - الأنشطة يجب أن تكون عملية وقابلة للتطبيق
   - ربط الأنشطة بالحالة المحددة
   - اكتب كل نشاط كعنصر منفصل في المصفوفة

5. بيئة التعلم (environment):
   - وصف البيئة التعليمية المناسبة لدمج الحالة
   - حدد المتطلبات البيئية (المكان، الأدوات، الموارد)
   - وصف كيفية تهيئة البيئة لدعم دمج الحالة

6. أصحاب العلاقة (Stakeholders):
   - حدد جميع الأطراف المشاركة في دمج الحالة
   - لكل طرف: اذكر دوره ومسؤولياته في عملية الدمج
   - اكتب كل طرف كعنصر منفصل في المصفوفة
   - مثال: "المعلم: [وصف دوره ومسؤولياته]"

7. معيار / معايير المعلمين (teacher_criteria):
   - ربط الموقف بمعايير المعلمين المتاحة (القائمة الكاملة متوفرة أدناه)
   - راجع قائمة معايير المعلمين الكاملة واختر فقط المعايير ذات العلاقة الواضحة بالموقف
   - أدرج فقط أرقام المعايير (الكود) بدون أي تفاصيل أو شرح
   - مثال: إذا كان المعيار "1.1.4 - امتلاك المعرفة بنمو الطفل"، أدرج فقط "1.1.4"
   - يجب أن تكون المصفوفة تحتوي على رموز المعايير فقط (مثل: ["1.1.4", "2.3.1"])
   - اختر معايير مناسبة من المعايير الثلاثة الرئيسة: المعرفة المهنية، الممارسة المهنية، أخلاقيات المهنة والتنمية المهنية

متطلبات الجودة:
- اللغة: عربية فصحى مهنية ودقيقة
- العمق: تحليل عميق وليس سطحي
- الدقة: ربط واضح ومحدد بين الحالة والمعايير
- الشمولية: تغطية جميع جوانب دمج الحالة
- العملية: حلول واقعية وقابلة للتطبيق

هيكل JSON المطلوب (بدون قيم فارغة):
{
  "teacher_name": "اسم المعلم الطالب",
  "case": "الحالة",
  "case_description": "وصف الحالة",
  "reason_for_integration": "سبب دمج الحالة: [شرح مفصل يراعي التخصص]",
  "activities": ["نشاط 1 مناسب للتخصص", "نشاط 2 مناسب للتخصص", "..."],
  "environment": "بيئة التعلم: [وصف شامل]",
  "Stakeholders": ["طرف 1: [وصف]", "طرف 2: [وصف]", "..."],
  "teacher_criteria": ["1.1.4", "2.3.1", "..."]
}

ملاحظات مهمة:
- activities: يجب أن يكون مصفوفة (array) حيث كل عنصر يمثل نشاط واحد
- Stakeholders: يجب أن يكون مصفوفة (array) حيث كل عنصر يمثل طرف واحد
- teacher_criteria: يجب أن يكون مصفوفة (array) من أرقام المعايير فقط (الكود) بدون أي تفاصيل
- الحقول الأخرى: نصوص عادية (strings)

بروتوكول نقص المدخلات:
إذا كانت أي من المدخلات الجوهرية مفقودة (teacher_name, teacher_specialty, case, case_description)، أعد JSON بالهيئة التالية فقط:
{
  "need_more_info": ["اسم_الحقل_1", "اسم_الحقل_2"],
  "message": "يرجى تزويدي بالقيم الناقصة لاستكمال بناء السيناريو."
}

تذكير نهائي صارم:
- JSON فقط، بدون أي نص خارجي
- ابدأ مباشرة بـ { ولا تضع أي نص قبله
- انتهِ مباشرة بـ } ولا تضع أي نص بعده
- لا تستخدم markdown code blocks
- جميع الحقول مطلوبة (لا قيم فارغة)
USR;

        return $user;
    }

    /**
     * الحصول على قائمة معايير المعلمين الكاملة
     */
    private function getFullCriteriaList(): string
    {
        return <<<CRITERIA
قائمة معايير المعلمين الكاملة (للرجوع عند الربط):

المعيار الأول: المعرفة المهنية
1.1 المعرفة بالمبحث
• 1.1.1 فهم المعرفة بالمبحث أو المجال الذي سيتم تدريسه.
• 1.1.2 امتلاك المعرفة اللازمة بالمحتوى لإيجاد خبرة ذات صلة وذات مغزى للمتعلمين.
• 1.1.3 إجادة اللغة العربية أو الإنجليزية حسب المبحث.
• 1.1.4 امتلاك المعرفة بنمو الطفل (مع التركيز على الجانب النفسي للطفل).
• 1.1.5 فهم أنواع التقييم المختلفة للتعلم.

1.2 المعرفة بالمحتوى التربوي
• 1.2.1 امتلاك المعرفة التربوية المناسبة بالمحتوى للمتعلمين ومجال الدراسة.
• 1.2.2 فهم نظريات التعلم، وأهميتها في الممارسة.
• 1.2.3 معرفة وفهم مبادئ وممارسات التعلم والتعليم القائمة على الاستقصاء.

1.3 المعرفة بالسياق
• 1.3.1 فهم الثقافة والتقاليد الأردنية وتأثيرها على الممارسة.
• 1.3.2 القدرة على تحديد العوامل المتعلقة بخصائص المتعلم والبيئة الملائمة للتعلم.
• 1.3.3 القدرة على تحديد القضايا الرئيسة المتعلقة بالطلبة ذوي الاحتياجات التعليمية الخاصة وصعوبات التعلم.

1.4 المعرفة بالمنهاج
• 1.4.1 فهم متطلبات المنهاج الأردني.
• 1.4.2 فهم المبادئ الأساسية لتخطيط المناهج وتصميمها.
• 1.4.3 فهم المبادئ الأساسية لتقييم المنهاج.

المعيار الثاني: الممارسة المهنية
2.1 التخطيط
• 2.1.1 الاستخدام الفعال للمبحث والمعرفة بالمحتوى التربوي عند القيام بالتخطيط والتدريس وتقييم التعلم وتقويمه.
• 2.1.2 اختيار استراتيجيات التدريس ومصادره (تشمل أدوات التعلم الرقمية) وفقاً لحاجات الطلبة المختلفة.
• 2.1.3 التخطيط للتدريس لتلبية احتياجات جميع المتعلمين وتمكينهم من مواكبة متطلبات أعمارهم محلياً وعالمياً بنجاح.

2.2 التعلم والتعليم
• 2.2.1 التواصل بوضوح ودقة مع المتعلمين وأصحاب العلاقة.
• 2.2.2 إنشاء واستخدام مجموعة متسلسلة من الخبرات والأنشطة المرتبطة بأهداف تعليمية واضحة ومناسبة؛ لتعزيز إنجازات المتعلم.
• 2.2.3 صياغة توقعات عالية للمتعلمين وتحفيزهم والمحافظة على استدامتها.
• 2.2.4 جمع أدلة واستخدامها بشكل منهجي لتحسين التعليم والتعلم.
• 2.2.5 بناء حجج منطقية مترابطة حول القضايا والممارسات التعليمية.
• 2.2.6 توظيف أدوات التعلم الرقمية المناسبة في تطوير التعلم.

2.3 بيئة التعلم
• 2.3.1 إيجاد بيئة داعمة وآمنة للجميع والحفاظ عليها.
• 2.3.2 خلق بيئة تعليمية وإدارتها بشكل فعال لتمكين المتعلمين من التأمل بتعلمهم وتقييمه باستخدام التنظيم الذاتي.

2.4 التقييم
• 2.4.1 اعتماد نهج متوازن لاستخدام التقييم التكويني والختامي؛ لدعم تعلم الطلاب.
• 2.4.2 استخدام التمايز في التعلم والتعليم لتلبية احتياجات الطلاب على اختلاف قدراتهم.
• 2.4.3 جمع وتحليل واستخدام التقييم؛ لتحسين التعلم والكشف عن نقاط القوة والقصور في التخطيط.

المعيار الثالث: أخلاقيات المهنة والتنمية المهنية
3.1 المعلمون كمهنيين
• 3.1.1 العمل بفعالية مع المدرسة والمجتمع المحلي، بتوفير مستويات عالية من الخدمة.
• 3.1.2 فهم وتنفيذ المسؤوليات والحقوق المهنية بشكل كامل.
• 3.1.3 التعامل مع الآخرين بلطف واحترام ونزاهة.
• 3.1.4 استخدام الموارد بنزاهة وتثقيف المتعلمين للقيام بذلك.
• 3.1.5 إظهار الاحترام والتقدير والالتزام تجاه المجتمع الذي يعملون فيه.
• 3.1.6 إيجاد قنوات تواصل مثمرة مع أصحاب العلاقة والحفاظ عليها.

3.2 التنمية المهنية
• 3.2.1 إظهار المعرفة بضرورة الالتزام بالتطوير الشخصي والمهني مدى الحياة.
• 3.2.2 إظهار الوعي بالبحوث التربوية ومساهمتها في التعلم والتعليم.
• 3.2.3 التفكير بعمق في كيفية المساهمة الفعالة في تطوير المناهج الدراسية والتخطيط لتطوير المدارس.
• 3.2.4 تقدير المهنية من خلال تحمل الطلبة مسؤولية تعلمهم وتطورهم المهني.
CRITERIA;
    }
}

