<?php
declare(strict_types=1);

namespace App\Libraries\PromptMaker;

/**
 * FormativeReflectiveEssayPromptMaker: بناء توجيهات كتابة المقال التأملي التكويني
 */
class FormativeReflectiveEssayPromptMaker extends BasePromptMaker
{
    public function buildSystemPrompt(string $basePrompt, array $payload): string
    {
        if (trim($basePrompt) === '') {
            return <<<SYS
أنت خبير تربوي في تحليل وتقييم الممارسات التعليمية باستخدام نموذج جيبس (Gibbs Reflective Cycle).
مهمتك كتابة مقالة تأملية تكوينية لمعلم الدبلوم حول الممارسة المختارة في بيئة التعلم.
طول المقال: حوالي 1500 كلمة (بزيادة أو نقصان 10%).

تعليمات هامة جداً:
- يجب أن يكون المخرج عبارة عن كائن JSON صالح تماماً ويحتوي على مفتاحين فقط: "article_title" (العنوان المقترح للمقال) و "content" (محتوى المقال كاملاً).
- اكتب محتوى المقال بشكل متصل ومترابط دون استخدام أي عناوين فرعية (No Subheadings).
- استخدم تنسيق الفقرات العادية (Newlines) بين الأجزاء للانتقال بسلاسة دون عناوين واضحة للمراحل.
- المقالة يجب أن تتضمن جزأين رئيسيين مدمجين سياقياً:
  الجزء الأول: رحلتي في الدبلوم بوصفى معلماً مختصاً (المقدمة، الوصف دون تفسير، المشاعر، تقييم وتحليل الموقف مع ربطه بثلاثة مصادر تربوية، الاستنتاجات، خطة العمل).
  الجزء الثاني: أثر الدبلوم والتطوير المهني (أثر المساقات النظرية والتطبيقية، خطة عمل التحديات، الخاتمة).
SYS;
        }
        return trim($basePrompt);
    }

    public function buildUserPrompt(array $payload): string
    {
        $val = fn(?string $s): string => $this->cleanValue($s);

        $teacherSpecialty = $val($payload['teacher_specialty'] ?? '');
        $gradeLevel       = $val($payload['grade_level'] ?? '');
        $teacherNameId    = $val($payload['teacher_name_id'] ?? '');
        $situationDesc    = $val($payload['situation_description'] ?? 'موقف تعليمي عام داخل الغرفة الصفية يحتاج إلى تأمل وتطوير.');
        $taskTitle        = $val($payload['task_title'] ?? '');

        return <<<USR
IMPORTANT: Output MUST be JSON only with no extra text outside JSON.
Return exactly ONE valid JSON object with the following keys:
- "article_title": عنوان مناسب للمقال التأملي.
- "content": المقال الكامل كنص واحد (بفقرات مفصولة بأسطر جديدة دون عناوين فرعية).

البيانات المدخلة:
- عنوان المهمة: {$taskTitle}
- تخصص المعلم: {$teacherSpecialty}
- الصف الذي يدرسه: {$gradeLevel}
- وصف عام للموقف: {$situationDesc}
(ملاحظة هامة: يجب ألا يتضمن المقال التأملي اسم المعلم أو رقمه الوزاري "{$teacherNameId}" إطلاقاً.)

تعليمات إلزامية ومشددة لبناء محتوى "content":
1. [شرط صارم جداً]: يجب ألا يقل طول المقال بأي حال من الأحوال عن 1350 كلمة ولا يزيد عن 1650 كلمة. المخرجات القصيرة (مثل 1100 كلمة) مرفوضة تماماً. للوصول لهذا الطول، توسع جداً في السرد، التحليل، والمشاعر، وقدم أمثلة وشروحات معمقة.
2. لا تستخدم العناوين الفرعية أبداً، بل اكتب المقال كفقرات مترابطة بأسلوب سردي تأملي أكاديمي.
3. قسّم الأفكار في السرد إلى جزأين أساسيين مدمجين:
   أ. رحلتي في الدبلوم.
   ب. أثر الدبلوم والتطوير المهني.
4. ادمج التخصص ({$teacherSpecialty}) والمرحلة ({$gradeLevel}) في سياق المقال بذكاء.
5. لا تقم أبداً بكتابة أو ذكر اسم المعلم أو رقمه الوزاري داخل النص.
6. في فقرة التحليل والاستنتاج، وظّف مرجعين من المراجع العربية الحديثة (ما بعد عام 2015) مع توثيقها بنظام (MLA).
7. وظّف معايير المعلمين المرفقة أدناه، مع ذكر رقم المعيار في أي مكان مناسب حسب السياق ضمن المقال.
8. أضف قائمة المراجع (باللغة العربية) في نهاية المقال، مع تضمين المرجع التالي إلزامياً: "أكاديمية الملكة رانيا لتدريب المعلمين. معايير المعلمين. 2024." بالإضافة إلى المرجعين العربيين الحديثين.
9. لا تُدرج أي JSON أو شيفرة داخل الحقل "content".

إليك معايير المعلمين للتوظيف:
{$this->getTeacherStandards()}

أخرج النتيجة ككائن JSON فقط.
USR;
    }
}
